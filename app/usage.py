'''Privacy-minimised usage: SQLite local, PostgreSQL cloud. Best-effort telemetry only.'''
import os
import sqlite3
from contextlib import closing
from datetime import datetime, timezone
from pathlib import Path
from app.security import customer_context
from app.resilience import diagnostic

DEFAULT_DB = Path(__file__).resolve().parent.parent / ".agentverify" / "usage.sqlite3"
EMPTY = {"requests": 0, "calculations": 0, "passed": 0, "failed": 0, "by_operation": []}

def _environment(env=None):
    if env is not None:
        return env
    from app.startup import runtime_environment
    return runtime_environment()

def _db_path(env=None):
    return Path(_environment(env).get("AGENTVERIFY_USAGE_DB", str(DEFAULT_DB)))

def _backend(env=None):
    backend = _environment(env).get("AGENTVERIFY_USAGE_BACKEND", "sqlite").lower()
    if backend not in ("sqlite", "postgres"):
        raise ValueError("AGENTVERIFY_USAGE_BACKEND must be sqlite or postgres")
    return backend

def _postgres_url(env=None):
    url = _environment(env).get("AGENTVERIFY_DATABASE_URL", "")
    if not url.startswith(("postgresql://", "postgres://")):
        raise ValueError("PostgreSQL usage backend requires AGENTVERIFY_DATABASE_URL")
    return url

def _postgres_connection(env=None):
    import psycopg
    try:
        return psycopg.connect(_postgres_url(env), connect_timeout=5)
    except Exception as exc:
        diagnostic("connection_acquisition_failed", exc)
        raise

def _ensure_postgres_table(db, env=None):
    if _environment(env).get("AGENTVERIFY_POSTGRES_SCHEMA_MANAGED") == "1":
        return
    with db.cursor() as cur:
        cur.execute('''CREATE TABLE IF NOT EXISTS usage_events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            timestamp_utc TIMESTAMPTZ NOT NULL,
            source TEXT NOT NULL,
            operation TEXT NOT NULL,
            passed INTEGER NOT NULL,
            failed INTEGER NOT NULL
        )''')
        cur.execute('ALTER TABLE usage_events ADD COLUMN IF NOT EXISTS customer_id TEXT')
        cur.execute('CREATE INDEX IF NOT EXISTS usage_events_customer_id_idx ON usage_events(customer_id)')

def _record_postgres(source, operation, passed, failed):
    env = _environment()
    with closing(_postgres_connection(env)) as db, db:
        _ensure_postgres_table(db, env)
        with db.cursor() as cur:
            cur.execute('''INSERT INTO usage_events
                (timestamp_utc, source, operation, passed, failed, customer_id)
                VALUES (%s, %s, %s, %s, %s, %s)''',
                (datetime.now(timezone.utc), source, operation, passed, failed, customer_context.get()))

def _record_sqlite(source, operation, passed, failed):
    path = _db_path(_environment())
    path.parent.mkdir(parents=True, exist_ok=True)
    with closing(sqlite3.connect(path, timeout=3)) as db, db:
        db.execute('''CREATE TABLE IF NOT EXISTS usage_events (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp_utc TEXT NOT NULL,
            source TEXT NOT NULL,
            operation TEXT NOT NULL,
            passed INTEGER NOT NULL,
            failed INTEGER NOT NULL
        )''')
        columns = [row[1] for row in db.execute('PRAGMA table_info(usage_events)')]
        if 'customer_id' not in columns:
            db.execute('ALTER TABLE usage_events ADD COLUMN customer_id TEXT')
        db.execute('''INSERT INTO usage_events
            (timestamp_utc, source, operation, passed, failed, customer_id)
            VALUES (?, ?, ?, ?, ?, ?)''',
            (datetime.now(timezone.utc).isoformat(), source, operation, passed, failed, customer_context.get()))

def record(source: str, operation: str, passed: int, failed: int) -> None:
    env = _environment()
    if env.get("AGENTVERIFY_USAGE_ENABLED", "1") != "1":
        return
    try:
        if _backend(env) == "postgres":
            _record_postgres(source, operation, passed, failed)
        else:
            _record_sqlite(source, operation, passed, failed)
    except Exception as exc:
        diagnostic("usage_record_failed", exc)

def _format_summary(rows):
    return {
        "requests": sum(r[2] for r in rows),
        "calculations": sum(r[3] + r[4] for r in rows),
        "passed": sum(r[3] for r in rows),
        "failed": sum(r[4] for r in rows),
        "by_operation": [
            {"source": r[0], "operation": r[1], "requests": r[2],
             "passed": r[3], "failed": r[4]} for r in rows
        ],
    }

def summary() -> dict:
    env = _environment()
    if _backend(env) == "postgres":
        with closing(_postgres_connection(env)) as db, db:
            _ensure_postgres_table(db, env)
            with db.cursor() as cur:
                cur.execute('''SELECT source, operation, COUNT(*),
                    COALESCE(SUM(passed), 0), COALESCE(SUM(failed), 0)
                    FROM usage_events GROUP BY source, operation
                    ORDER BY source, operation''')
                rows = cur.fetchall()
        return _format_summary(rows)
    path = _db_path(env)
    if not path.exists():
        return dict(EMPTY)
    with closing(sqlite3.connect(path, timeout=3)) as db, db:
        rows = db.execute('''SELECT source, operation, COUNT(*), SUM(passed), SUM(failed)
            FROM usage_events GROUP BY source, operation ORDER BY source, operation''').fetchall()
    return _format_summary(rows)

def customer_summary(customer: str) -> dict:
    '''Internal-only query, not exposed as an HTTP endpoint.''' 
    env = _environment()
    if _backend(env) != 'postgres':
        raise RuntimeError('Customer summary requires PostgreSQL')
    with closing(_postgres_connection(env)) as db, db:
        _ensure_postgres_table(db, env)
        with db.cursor() as cur:
            cur.execute('''SELECT source, operation, COUNT(*),
                COALESCE(SUM(passed), 0), COALESCE(SUM(failed), 0)
                FROM usage_events WHERE customer_id = %s
                GROUP BY source, operation ORDER BY source, operation''', (customer,))
            return _format_summary(cur.fetchall())

if __name__ == "__main__":
    import json
    print(json.dumps(summary(), indent=2))
