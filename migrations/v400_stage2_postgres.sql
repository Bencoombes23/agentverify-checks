CREATE TABLE IF NOT EXISTS agentverify_schema (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    version TEXT NOT NULL
);

DO $agentverify$
DECLARE current_version TEXT;
BEGIN
    IF (SELECT COUNT(*) FROM agentverify_schema) > 1 THEN
        RAISE EXCEPTION 'agentverify schema metadata is ambiguous';
    END IF;
    SELECT version INTO current_version FROM agentverify_schema WHERE singleton=TRUE;
    IF current_version IS NULL THEN
        INSERT INTO agentverify_schema(singleton, version) VALUES (TRUE, '4.00-stage2-1');
    ELSIF current_version <> '4.00-stage2-1' THEN
        RAISE EXCEPTION 'unsupported agentverify schema version';
    END IF;
END
$agentverify$;

CREATE TABLE IF NOT EXISTS usage_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp_utc TIMESTAMPTZ NOT NULL,
    source TEXT NOT NULL,
    operation TEXT NOT NULL,
    passed INTEGER NOT NULL,
    failed INTEGER NOT NULL,
    customer_id TEXT
);
ALTER TABLE usage_events ADD COLUMN IF NOT EXISTS customer_id TEXT;
CREATE INDEX IF NOT EXISTS usage_events_customer_id_idx ON usage_events(customer_id);

CREATE TABLE IF NOT EXISTS customer_daily_quotas (
    customer_id TEXT NOT NULL,
    day_utc DATE NOT NULL,
    used BIGINT NOT NULL CHECK (used >= 0),
    PRIMARY KEY (customer_id, day_utc)
);

CREATE TABLE IF NOT EXISTS verification_idempotency (
    tenant_id TEXT NOT NULL,
    route TEXT NOT NULL,
    idempotency_key TEXT NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('in_progress','committed','blocked')),
    owner_token CHAR(64) NOT NULL,
    response_status SMALLINT,
    response_body TEXT,
    response_sha256 CHAR(64),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    retain_until TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (tenant_id, route, idempotency_key),
    CHECK ((state='committed') =
           (response_status IS NOT NULL AND response_body IS NOT NULL AND
            response_sha256 IS NOT NULL))
);
